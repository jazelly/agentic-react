#!/usr/bin/env node
/**
 * Convert benchmark/tasks/<repo>/<task>/task.json → Harbor task packages under
 * vendor/agentic-react-harbor/tasks/<repo>__<task-slug>/.
 *
 * Re-run anytime; output is deterministic from task.json + manifest.json.
 *   node scripts/convert-to-harbor.mjs [--filter <substr>] [--out <dir>]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { listTasks, repoById, reverseEdits, BENCH } from '../lib/task-kit.mjs';

const args = process.argv.slice(2);
const arg = (k, d) => {
  const i = args.indexOf(`--${k}`);
  return i >= 0 ? args[i + 1] : d;
};
const filter = arg('filter', args.find((a) => !a.startsWith('--')) ?? '');
const outRoot = path.resolve(BENCH, arg('out', 'vendor/agentic-react-harbor/tasks'));
const runtimeDir = path.join(BENCH, 'harbor-runtime');

const harborSlug = (taskId) => taskId.replace(/\//g, '__');

function solutionEdits(task) {
  if (task.solution === 'reverse-setup') return reverseEdits(task.setup?.edits ?? []);
  if (Array.isArray(task.solution)) return task.solution;
  return null; // no oracle
}

function needsPlaywrightBrowsers(task) {
  return (task.check?.steps ?? []).some((s) => {
    if (s.optional) return false; // optional browser steps skipped unless BENCH_INCLUDE_OPTIONAL=1
    return (
      s.type === 'browser' ||
      (s.type === 'hidden-test' && /--browser|browser\.headless|playwright/i.test(String(s.run ?? '')))
    );
  });
}

/** Pick a Node base image that satisfies the pinned repo's engines.node. */
function nodeDockerImage(repo) {
  if (repo.harbor?.nodeImage) return repo.harbor.nodeImage;
  const engines = repo.engines?.node ?? '';
  // Caret-only Node 22 ranges reject Node 24 under pnpm engine-strict.
  if (/^\^22(\.|$)/.test(engines.trim()) && !engines.includes('||')) return 'node:22-bookworm';
  // Default Node 24: jsoncrack / Next 16 / Astro ^24.16 all need it.
  return 'node:24-bookworm';
}

function dockerfileFor(repo, task) {
  const appDir = repo.appDir ?? '.';
  const sparsePaths = (repo.sparse ?? []).map((p) => JSON.stringify(p)).join(' ');
  const sparseBlock = repo.sparse?.length
    ? ` && git sparse-checkout init --cone && git sparse-checkout set ${sparsePaths}`
    : '';
  const install = repo.commands?.install ?? 'echo "no install command"';
  const pmHint =
    repo.packageManager?.startsWith('pnpm') || install.includes('pnpm')
      ? 'pnpm'
      : repo.packageManager?.startsWith('yarn') || install.includes('yarn')
        ? 'yarn'
        : 'npm';
  const workdirApp = appDir === '.' ? '/app' : `/app/${appDir}`;
  // Install at repo root unless commandsCwd is appDir (e.g. tanstack example).
  const installWorkdir = repo.commandsCwd === 'appDir' ? workdirApp : '/app';
  const nodeImage = nodeDockerImage(repo);
  const enginesNote = repo.engines?.node
    ? `engines.node ${repo.engines.node}`
    : 'no engines.node pin (default)';

  // pnpm ≥10 may refuse lifecycle scripts unless builds are approved (breaks esbuild etc. in CI images).
  // Must use `pnpm config set` — a bare .npmrc key is ignored by pnpm 12.21 in our smoke test.
  const pnpmAllowBuilds =
    pmHint === 'pnpm' ? 'pnpm config set dangerouslyAllowAllBuilds true && ' : '';

  // Vitest browser / Playwright hidden-tests need chromium in the image (host `test:browser:install`).
  const playwrightBlock = needsPlaywrightBrowsers(task)
    ? `
# Playwright chromium for browser-mode checks (hidden-test / browser steps).
WORKDIR ${workdirApp}
RUN if [ -x node_modules/.bin/playwright ]; then \\
      ./node_modules/.bin/playwright install chromium --with-deps; \\
    elif command -v pnpm >/dev/null && pnpm exec playwright --version >/dev/null 2>&1; then \\
      pnpm exec playwright install chromium --with-deps; \\
    else \\
      npx --yes playwright@1.59.1 install chromium --with-deps; \\
    fi
WORKDIR /app
`
    : '';

  // next/font/google fetches fonts.googleapis.com at build time — flaky ETIMEDOUT in Docker.
  // Prefetch into the image and point Next at a mock map (absolute /path woff2 reads).
  const needsGoogleFonts =
    repo.harbor?.prefetchGoogleFonts === true ||
    repo.id === 'next-webpack-jsoncrack' ||
    repo.id === 'next-turbopack-boilerplate';
  const googleFontsBlock = needsGoogleFonts
    ? `
COPY prefetch-google-fonts.mjs /opt/bench/prefetch-google-fonts.mjs
RUN node /opt/bench/prefetch-google-fonts.mjs --out /opt/bench --app "${workdirApp}"
ENV NEXT_FONT_GOOGLE_MOCKED_RESPONSES=/opt/bench/mocked-google-fonts.cjs
`
    : '';

  // Some Next apps gitignore next-env.d.ts; `tsc --noEmit` needs `next typegen` first.
  const needsNextTypegen = repo.harbor?.nextTypegen === true || repo.id === 'next-turbopack-boilerplate';
  const nextTypegenBlock = needsNextTypegen
    ? `
# Generate next-env.d.ts + .next/types (not committed upstream).
WORKDIR ${workdirApp}
RUN npx next typegen
WORKDIR /app
`
    : '';

  return `# Generated by scripts/convert-to-harbor.mjs — do not edit by hand.
# Base image ${nodeImage} (${enginesNote}).
FROM ${nodeImage}

RUN apt-get update -qq \\
 && apt-get install -y -qq git ca-certificates python3 \\
 && rm -rf /var/lib/apt/lists/* \\
 && corepack enable

WORKDIR /app

ARG REPO_URL=${JSON.stringify(repo.repo)}
ARG BASE_SHA=${JSON.stringify(repo.sha)}
ENV BENCH_APP_DIR=${JSON.stringify(appDir)}
ENV BENCH_REPO_ID=${JSON.stringify(repo.id)}
ENV BENCH_TASK_ID=${JSON.stringify(task.id)}

# Pin to BASE_SHA on a real branch with no future history / remotes.
# Full clone (not --filter=blob:none): partial clones break under git gc --prune.
RUN git clone${repo.sparse?.length ? ' --sparse' : ''} "$REPO_URL" . \\
 && DEFAULT="$(git remote show origin | sed -n 's/.*HEAD branch: //p')" \\
 && DEFAULT="\${DEFAULT:-main}"${sparseBlock} \\
 && git checkout -B "$DEFAULT" "$BASE_SHA" \\
 && git remote remove origin \\
 && for b in $(git for-each-ref --format='%(refname:short)' refs/heads | grep -vx "$DEFAULT"); do git branch -D "$b" || true; done \\
 && for t in $(git tag); do git merge-base --is-ancestor "$t" HEAD 2>/dev/null || git tag -d "$t"; done \\
 && git reflog expire --expire=now --all \\
 && (git gc --prune=now || true) \\
 && (git submodule update --init --recursive || true)

COPY apply-edits.mjs /opt/bench/apply-edits.mjs
COPY setup-edits.json /opt/bench/setup-edits.json
RUN node /opt/bench/apply-edits.mjs "${workdirApp}" /opt/bench/setup-edits.json

# Package manager install (from manifest.json). ${pmHint}
WORKDIR ${installWorkdir}
RUN ${pnpmAllowBuilds}${install}
WORKDIR /app
${googleFontsBlock}${nextTypegenBlock}${playwrightBlock}
# Scratch baseline: agent / oracle diffs are relative to post-setup tree.
RUN git config user.email bench@local \\
 && git config user.name bench \\
 && git config core.hooksPath /dev/null \\
 && git add -A \\
 && git commit -qm bench-baseline --allow-empty --no-verify

CMD ["/bin/bash"]
`;
}

function taskToml(repo, task) {
  const timeoutMin = task.budget?.timeoutMin ?? 30;
  const agentTimeout = timeoutMin * 60;
  const verifierTimeout = Math.max(900, timeoutMin * 30);
  return `schema_version = "1.4"

[task]
name = "agentic-react/${harborSlug(task.id)}"
version = "1.0.0"
description = ${JSON.stringify(task.prompt.slice(0, 200))}
keywords = ["react", "agentic-react", ${JSON.stringify(task.category)}, ${JSON.stringify(repo.bundler)}]

[metadata]
category = ${JSON.stringify(task.category)}
repo_id = ${JSON.stringify(repo.id)}
source_task_id = ${JSON.stringify(task.id)}
bundler = ${JSON.stringify(repo.bundler)}
framework = ${JSON.stringify(repo.framework)}
source = "converted from benchmark/tasks via scripts/convert-to-harbor.mjs"

[verifier]
timeout_sec = ${verifierTimeout}.0
environment_mode = "shared"

[agent]
timeout_sec = ${agentTimeout}.0

[environment]
build_timeout_sec = 3600.0
cpus = 2
memory_mb = 8192
storage_mb = 40960
gpus = 0
`;
}

function testSh() {
  return `#!/bin/bash
# Harbor verifier entrypoint — grades via check.steps (same semantics as lib/task-kit.mjs).
set -uo pipefail
mkdir -p /logs/verifier
echo 0 > /logs/verifier/reward.txt
echo 0 > /logs/verifier/reward.json 2>/dev/null || true

cd /app || { echo "missing /app"; exit 6; }

if node /tests/check-runner.mjs /tests/task-check.json; then
  echo 1 > /logs/verifier/reward.txt
  printf '{"reward":1}\\n' > /logs/verifier/reward.json
  exit 0
fi

printf '{"reward":0}\\n' > /logs/verifier/reward.json
exit 0
`;
}

function solveSh(hasSolution) {
  if (!hasSolution) {
    return `#!/bin/bash
set -euo pipefail
echo "No reference solution for this task (oracle not provided)." >&2
exit 1
`;
  }
  return `#!/bin/bash
set -euo pipefail
cd /app
APP_DIR="\${BENCH_APP_DIR:-.}"
node /solution/apply-edits.mjs "/app/\${APP_DIR}" /solution/solution-edits.json
git add -A
git -c user.email=oracle@local -c user.name=oracle commit -qm "oracle solution" --allow-empty --no-verify || true
`;
}

fs.mkdirSync(outRoot, { recursive: true });
let n = 0;
const skipped = [];

for (const task of listTasks(filter)) {
  const repo = repoById(task.repo);
  const slug = harborSlug(task.id);
  const dest = path.join(outRoot, slug);
  fs.rmSync(dest, { recursive: true, force: true });
  fs.mkdirSync(path.join(dest, 'environment'), { recursive: true });
  fs.mkdirSync(path.join(dest, 'tests'), { recursive: true });
  fs.mkdirSync(path.join(dest, 'solution'), { recursive: true });

  const sol = solutionEdits(task);
  const setupEdits = task.setup?.edits ?? [];

  fs.writeFileSync(path.join(dest, 'task.toml'), taskToml(repo, task));
  fs.writeFileSync(path.join(dest, 'instruction.md'), task.prompt.trim() + '\n');
  fs.writeFileSync(path.join(dest, 'environment', 'Dockerfile'), dockerfileFor(repo, task));
  fs.copyFileSync(path.join(runtimeDir, 'apply-edits.mjs'), path.join(dest, 'environment', 'apply-edits.mjs'));
  const copyGoogleFontsPrefetch =
    repo.harbor?.prefetchGoogleFonts === true ||
    repo.id === 'next-webpack-jsoncrack' ||
    repo.id === 'next-turbopack-boilerplate';
  if (copyGoogleFontsPrefetch && fs.existsSync(path.join(runtimeDir, 'prefetch-google-fonts.mjs'))) {
    fs.copyFileSync(
      path.join(runtimeDir, 'prefetch-google-fonts.mjs'),
      path.join(dest, 'environment', 'prefetch-google-fonts.mjs'),
    );
  }
  fs.writeFileSync(path.join(dest, 'environment', 'setup-edits.json'), JSON.stringify(setupEdits, null, 2) + '\n');

  // Verifier
  fs.writeFileSync(path.join(dest, 'tests', 'test.sh'), testSh(), { mode: 0o755 });
  fs.chmodSync(path.join(dest, 'tests', 'test.sh'), 0o755);
  fs.copyFileSync(path.join(runtimeDir, 'check-runner.mjs'), path.join(dest, 'tests', 'check-runner.mjs'));

  const hiddenDir = path.join(task.dir, 'hidden');
  let hasHidden = false;
  if (fs.existsSync(hiddenDir)) {
    fs.cpSync(hiddenDir, path.join(dest, 'tests', 'hidden'), { recursive: true });
    hasHidden = true;
  }

  const taskCheck = {
    appDir: repo.appDir ?? '.',
    commands: repo.commands ?? {},
    commandsCwd: repo.commandsCwd,
    check: task.check ?? { steps: [] },
    hiddenBase: hasHidden ? '/tests/hidden' : undefined,
  };
  fs.writeFileSync(path.join(dest, 'tests', 'task-check.json'), JSON.stringify(taskCheck, null, 2) + '\n');

  // Solution / oracle
  fs.copyFileSync(path.join(runtimeDir, 'apply-edits.mjs'), path.join(dest, 'solution', 'apply-edits.mjs'));
  fs.writeFileSync(path.join(dest, 'solution', 'solve.sh'), solveSh(!!sol), { mode: 0o755 });
  fs.chmodSync(path.join(dest, 'solution', 'solve.sh'), 0o755);
  fs.writeFileSync(
    path.join(dest, 'solution', 'solution-edits.json'),
    JSON.stringify(sol ?? [], null, 2) + '\n',
  );
  if (!sol) skipped.push(`${task.id}: no oracle solution`);

  n++;
  console.log(`wrote ${path.relative(BENCH, dest)}`);
}

const listDir = path.join(BENCH, 'suites/agentic-react');
fs.mkdirSync(listDir, { recursive: true });
const slugs = fs.readdirSync(outRoot).filter((d) => fs.existsSync(path.join(outRoot, d, 'task.toml'))).sort();
fs.writeFileSync(path.join(listDir, 'tasks.txt'), slugs.join('\n') + '\n');
fs.writeFileSync(
  path.join(listDir, 'README.md'),
  `# agentic-react Harbor suite\n\nGenerated task list for primase (\`suites.json\`).\n\nRegenerate:\n\n\`\`\`bash\nnode scripts/convert-to-harbor.mjs\nnode scripts/prepare-variants.mjs\n\`\`\`\n`,
);

console.log(`\nconverted ${n} Harbor tasks → ${path.relative(BENCH, outRoot)}`);
console.log(`wrote suites/agentic-react/tasks.txt (${slugs.length} tasks)`);
if (skipped.length) {
  console.log('oracle gaps:');
  for (const s of skipped) console.log(`  - ${s}`);
}
