// Task x stack matrix from task.json applicability + latest oracle result per pair. Writes MATRIX.md and results/matrix.csv
// usage: node harness/matrix.mjs [taskFilter=core10]
import fs from 'node:fs';
import path from 'node:path';
import { listTasks, STACK_IDS, stackStatus, loadStack, RESULTS, XS } from './lib.mjs';

const filter = process.argv[2] ?? 'core10';
const latest = new Map();
for (const f of fs.readdirSync(RESULTS).filter((f) => f.startsWith('oracle-')).sort()) {
  for (const l of fs.readFileSync(path.join(RESULTS, f), 'utf8').split('\n').filter(Boolean)) {
    const r = JSON.parse(l); latest.set(`${r.task}|${r.stack}`, r);
  }
}
const AGENTIC = {
  'vite-spa': 'yes: MCP + source lookup verified',
  webpack5: 'yes: MCP + source lookup verified',
  rsbuild: 'NO adapter -> agentic == baseline',
  'next-turbopack': 'NO adapter (Next adapter hooks webpack only) -> agentic == baseline',
  'tanstack-start': 'partial: /mcp up, browser runtime NOT injected (adapter uses transformIndexHtml; SSR has no index.html)',
  'react-router-7': 'partial: /mcp up, browser runtime NOT injected (same reason)',
  astro: 'partial: /mcp up, browser runtime NOT injected (same reason)',
};
const tasks = listTasks(filter);
const rows = []; const counts = { pass: 0, fail: 0, na: 0, todo: 0 };
for (const t of tasks) {
  const cells = STACK_IDS.map((s) => {
    const st = stackStatus(t, s);
    if (st.status === 'na') { counts.na++; return { s, cell: 'N/A', note: st.reason }; }
    const r = latest.get(`${t.id}|${s}`);
    if (!r) { counts.todo++; return { s, cell: 'todo' }; }
    if (r.ok) { counts.pass++; return { s, cell: 'ported ✓' }; }
    counts.fail++; return { s, cell: 'ported ✗', note: JSON.stringify(r.failedSteps?.solution?.map((x) => x.type) ?? r.error?.slice(0, 80)) };
  });
  rows.push({ t, cells });
}
let md = `# Task × stack matrix (${filter})\n\nGenerated by \`node harness/matrix.mjs ${filter}\` from task.json + latest oracle run per pair. Oracle = hidden verifier FAILS on the initial state and PASSES on the reference solution, on that stack's production server.\n\n`;
md += `Counts: ${tasks.length} tasks × ${STACK_IDS.length} stacks = ${tasks.length * STACK_IDS.length} combos; ported ✓ ${counts.pass}, ported ✗ ${counts.fail}, N/A ${counts.na}, todo ${counts.todo}.\n\n`;
md += `| task | suite | category | ${STACK_IDS.join(' | ')} |\n|---|---|---|${STACK_IDS.map(() => '---').join('|')}|\n`;
for (const { t, cells } of rows) md += `| ${t.id} | ${t.suite} | ${t.category} | ${cells.map((c) => c.cell).join(' | ')} |\n`;
md += `\n## Agentic arm per stack\n\n| stack | bundler / framework | agentic-react adapter |\n|---|---|---|\n`;
for (const s of STACK_IDS) { const st = loadStack(s); md += `| ${s} | ${st.bundler} / ${st.framework} | ${AGENTIC[s]} |\n`; }
const notes = rows.flatMap(({ t, cells }) => cells.filter((c) => c.note).map((c) => `- ${t.id} @ ${c.s}: ${c.cell} — ${c.note}`));
if (notes.length) md += `\n## Notes\n\n${[...new Set(notes)].join('\n')}\n`;
fs.writeFileSync(path.join(XS, 'MATRIX.md'), md);
fs.writeFileSync(path.join(RESULTS, 'matrix.csv'), ['task,' + STACK_IDS.join(','), ...rows.map(({ t, cells }) => [t.id, ...cells.map((c) => c.cell)].join(','))].join('\n') + '\n');
console.log(md.split('\n').slice(0, 20).join('\n'));
